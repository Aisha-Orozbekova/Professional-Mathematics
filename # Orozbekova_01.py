import math


# ============================================================
# ДЗ №1, задача 18
# Сначала приводим угол x = 9.85 рад к промежутку
# [-pi/2, pi/2] с помощью периодичности и симметрии.
# Затем вычисляем sin(x) рядом Маклорена до тех пор,
# пока модуль следующего члена не станет меньше 10^-6.
# ============================================================

print("=" * 60)
print("ДЗ №1, задача 18")

x = 9.85
eps = 1e-6

# Приводим угол к промежутку [-pi, pi]
x_red = x % (2 * math.pi)

if x_red > math.pi:
    x_red -= 2 * math.pi

# Приводим угол к промежутку [-pi/2, pi/2]
sign = 1

if x_red > math.pi / 2:
    # sin(pi - x) = sin(x)
    x_red = math.pi - x_red

elif x_red < -math.pi / 2:
    # sin(x + pi) = -sin(x)
    x_red = x_red + math.pi
    sign = -1

print(f"Исходный угол: {x} рад")
print(f"Приведённый угол: {x_red:.12f} рад")
print(f"Знак: {sign}")

# Ряд Маклорена:
# sin(x) = x - x^3/3! + x^5/5! - ...

term = x_red
sin_series = term

# Первый член уже добавлен
number_of_terms = 1
k = 1

while True:
    # Вычисляем следующий член рекуррентно
    # без использования факториалов
    term = -term * x_red**2 / ((2 * k) * (2 * k + 1))

    # Если следующий член меньше eps,
    # его уже не добавляем в сумму
    if abs(term) < eps:
        break

    sin_series += term
    number_of_terms += 1
    k += 1

# Возвращаем правильный знак
sin_series *= sign

print(f"Сумма ряда: {sin_series:.12f}")
print(f"Проверка math.sin: {math.sin(x):.12f}")
print(f"Абсолютная погрешность: {abs(sin_series - math.sin(x)):.3e}")
print(f"Число использованных членов: {number_of_terms}")


# ============================================================
# ДЗ №1, задача 19
# Составить псевдокод вычисления cos(x) без степеней
# и факториалов, используя рекуррентное отношение:
#
# t_(k+1) = -t_k * x^2 / ((2k+1)(2k+2))
#
# Для x = 0.58 и eps = 10^-8 указать сумму
# и число членов.
# ============================================================

print("=" * 60)
print("ДЗ №1, задача 19")

x = 0.58
eps = 1e-8

# Псевдокод:
#
# term = 1
# S = term
# k = 0
#
# пока следующий член по модулю >= eps:
#     next_term = -term * x^2 / ((2k+1)(2k+2))
#     S = S + next_term
#     term = next_term
#     k = k + 1
#
# вывести S и количество членов

term = 1.0
S = term
k = 0

while True:
    # Используем x * x вместо x**2,
    # так как по условию нельзя использовать степени
    next_term = -term * x * x / ((2 * k + 1) * (2 * k + 2))

    if abs(next_term) < eps:
        break

    term = next_term
    S += term
    k += 1

number_of_terms = k + 1

print(f"x = {x}")
print(f"eps = {eps}")
print(f"Сумма cos(x): {S:.12f}")
print(f"Число членов: {number_of_terms}")


# ============================================================
# ДЗ №1, задача 20
# Вычислить F(t) = e^t * cos(t) при t = 0.29
# без использования math.exp() и math.cos().
#
# Оба ряда суммируем до тех пор, пока модуль
# следующего члена не станет меньше 10^-8.
#
# В конце библиотечные функции используются только
# для проверки абсолютной погрешности.
# ============================================================

print("=" * 60)
print("ДЗ №1, задача 20")

t = 0.29
eps = 1e-8


# ------------------------------------------------------------
# Ряд для e^t
#
# e^t = 1 + t + t^2/2! + t^3/3! + ...
#
# Рекуррентное отношение:
# a_(n+1) = a_n * t / (n + 1)
# ------------------------------------------------------------

term_exp = 1.0
sum_exp = term_exp

n = 0
number_exp_terms = 1

while True:

    next_term = term_exp * t / (n + 1)

    if abs(next_term) < eps:
        break

    sum_exp += next_term
    term_exp = next_term

    n += 1
    number_exp_terms += 1


# ------------------------------------------------------------
# Ряд для cos(t)
#
# cos(t) = 1 - t^2/2! + t^4/4! - ...
#
# Рекуррентное отношение:
# t_(k+1) = -t_k * t^2 / ((2k+1)(2k+2))
# ------------------------------------------------------------

term_cos = 1.0
sum_cos = term_cos

k = 0
number_cos_terms = 1

while True:

    next_term = -term_cos * t * t / ((2 * k + 1) * (2 * k + 2))

    if abs(next_term) < eps:
        break

    sum_cos += next_term
    term_cos = next_term

    k += 1
    number_cos_terms += 1


# F(t) вычисляем только через самостоятельно
# полученные суммы двух рядов

F = sum_exp * sum_cos


# Библиотечные функции используются только
# для проверки результата

exact_F = math.exp(t) * math.cos(t)

error = abs(F - exact_F)


print(f"t = {t}")
print(f"Сумма ряда e^t: {sum_exp:.12f}")
print(f"Число членов ряда e^t: {number_exp_terms}")
print(f"Сумма ряда cos(t): {sum_cos:.12f}")
print(f"Число членов ряда cos(t): {number_cos_terms}")
print(f"F(t) = e^t * cos(t): {F:.12f}")
print(f"Библиотечное значение: {exact_F:.12f}")
print(f"Абсолютная ошибка: {error:.3e}")